#!/usr/bin/env python3
"""Generate results tables from Inspect AI `.eval` logs.

Usage (from anywhere):
    python3 results/generate_results.py [--task humaneval] [--machine m1-8gb] [--force]

For every `results/<task>/<machine-id>/` folder that contains `.eval` logs it
writes `results.md` next to the logs (accuracy table, speed table, runs that did
not complete). For every task it also writes `results/<task>/comparison.md`,
which compares machines side by side.

Run metadata (quantization, context length, reasoning on/off, runtime) is resolved per run in this
order, and shown as "—" when unknown:
  1. the log's own metadata (`run.sh ... --metadata quant=... ctx=... reasoning=off runtime=...`)
  2. `results/<task>/<machine-id>/run-metadata.json`, for logs recorded before
     tagging was introduced:
       {"defaults": {"runtime": "...", "ctx": 8192, "reasoning": "off"},
        "models": {"openai/<model-id>": {"ctx": 512, "quant": "Q4_K_M"}}}
  3. the quantization parsed from the model name (e.g. `@8bit`, `-4bit`, `Q4_K_M`)

Only the Python standard library is used. Generated files start with a marker
line; the script refuses to overwrite a file without it unless `--force`.
"""
import argparse
import json
import re
import sys
import zipfile
from datetime import datetime
from pathlib import Path

RESULTS_DIR = Path(__file__).resolve().parent
MACHINES_DIR = RESULTS_DIR.parent / "machines"
MARKER = "<!-- generated by results/generate_results.py; do not edit by hand -->"
META_KEYS = ("quant", "ctx", "reasoning", "runtime")
DASH = "—"

QUANT_PATTERNS = [
    (re.compile(r"[@\-_ ](\d{1,2}bit)\b", re.I), str.lower),
    (re.compile(r"[@\-_ ](Q\d(?:_K(?:_[SML])?|_\d)?)\b", re.I), str.upper),
    (re.compile(r"[@\-_ ](fp16|bf16|fp8|int8|int4)\b", re.I), str.lower),
]


# --------------------------------------------------------------------------
# Reading logs
# --------------------------------------------------------------------------
def quant_from_name(model):
    for pattern, norm in QUANT_PATTERNS:
        match = pattern.search(model)
        if match:
            return norm(match.group(1))
    return None


def read_log(path):
    """Return a dict describing one `.eval` log, or None if unreadable."""
    try:
        with zipfile.ZipFile(path) as z:
            names = z.namelist()
            header = json.loads(z.read("header.json")) if "header.json" in names else None
            start = (
                json.loads(z.read("_journal/start.json"))
                if "_journal/start.json" in names
                else None
            )
            info = header or start
            if info is None:
                print(f"warning: {path.name}: no header.json or start.json, skipped",
                      file=sys.stderr)
                return None
            calls = []  # (output_tokens, seconds) per model call
            for name in names:
                if name.startswith("samples/") and name.endswith(".json"):
                    output = json.loads(z.read(name)).get("output") or {}
                    usage = output.get("usage") or {}
                    if output.get("time") is not None and usage.get("output_tokens") is not None:
                        calls.append((usage["output_tokens"], output["time"]))
    except (zipfile.BadZipFile, json.JSONDecodeError, KeyError) as exc:
        print(f"warning: {path.name}: unreadable ({exc}), skipped", file=sys.stderr)
        return None

    ev = info["eval"]
    model = ev["model"]
    status = header.get("status") if header else None
    completed = status == "success"
    stats = (header or {}).get("stats") or {}

    accuracy = metric = None
    scores = ((header or {}).get("results") or {}).get("scores") or []
    if completed and scores:
        metrics = scores[0].get("metrics") or {}
        metric = "accuracy" if "accuracy" in metrics else next(iter(metrics), None)
        if metric:
            accuracy = metrics[metric]["value"] * 100

    rates = [tokens / secs for tokens, secs in calls if secs > 0]
    usage = (stats.get("model_usage") or {}).get(model)
    out_tokens = usage["output_tokens"] if completed and usage else sum(t for t, _ in calls)

    wall = None
    if stats.get("started_at") and stats.get("completed_at"):
        wall = (datetime.fromisoformat(stats["completed_at"])
                - datetime.fromisoformat(stats["started_at"])).total_seconds()

    return {
        "file": path.name,
        "date": path.name[:10],
        "eval_id": ev["eval_id"],
        "model": model,
        "status": status,
        "completed": completed,
        "samples": len(calls),
        "total_samples": (ev.get("dataset") or {}).get("samples"),
        "metric": metric,
        "accuracy": accuracy,
        "out_tokens": out_tokens if (calls or usage) else None,
        "tps_avg": sum(rates) / len(rates) if rates else None,
        "tps_min": min(rates) if rates else None,
        "tps_max": max(rates) if rates else None,
        "wall_tps": out_tokens / wall if wall and wall > 0 and out_tokens else None,
        "log_metadata": ev.get("metadata") or {},
    }


def load_overrides(machine_dir):
    path = machine_dir / "run-metadata.json"
    return json.loads(path.read_text()) if path.exists() else {}


def resolve_metadata(run, overrides, machine_id):
    logged = run["log_metadata"]
    if logged.get("machine") not in (None, machine_id):
        print(f"warning: {run['file']}: tagged machine '{logged['machine']}' "
              f"but stored under '{machine_id}'", file=sys.stderr)
    model_overrides = (overrides.get("models") or {}).get(run["model"], {})
    defaults = overrides.get("defaults") or {}
    for key in META_KEYS:
        value = logged.get(key)
        if value is None:
            value = model_overrides.get(key)
        if value is None:
            value = defaults.get(key)
        if value is None and key == "quant":
            value = quant_from_name(run["model"])
        run[key] = value


# --------------------------------------------------------------------------
# Formatting
# --------------------------------------------------------------------------
def display_model(model):
    return model[len("openai/"):] if model.startswith("openai/") else model


def fmt(value, kind=None):
    if value is None:
        return DASH
    if kind == "pct":
        return f"{value:.1f}%"
    if kind == "int":
        return f"{value:,}"
    if kind == "rate":
        return f"{value:.1f}"
    return str(value)


def fmt_range(low, high):
    return DASH if low is None else f"{low:.1f}–{high:.1f}"


def fmt_ctx(run):
    """Context length followed by the reasoning setting, e.g. `8192 (off)`."""
    return f"{fmt(run['ctx'])} ({fmt(run['reasoning'])})"


def fmt_speed(run):
    """Per-call tok/s as `avg (min–max)`, e.g. `1.2 (0.1–9.0)`."""
    if run["tps_avg"] is None:
        return DASH
    return f"{run['tps_avg']:.1f} ({fmt_range(run['tps_min'], run['tps_max'])})"


def md_table(headers, rows, right=()):
    """Render a Markdown table; columns named in `right` are right-aligned."""
    cells = [[str(c) for c in row] for row in rows]
    widths = [max([len(h)] + [len(r[i]) for r in cells]) for i, h in enumerate(headers)]

    def line(values):
        return "| " + " | ".join(
            v.rjust(w) if headers[i] in right else v.ljust(w)
            for i, (v, w) in enumerate(zip(values, widths))
        ) + " |"

    sep = "|" + "|".join(
        "-" * (w + 1) + (":" if headers[i] in right else "-") for i, w in enumerate(widths)
    ) + "|"
    return "\n".join([line(headers), sep] + [line(r) for r in cells])


def machine_label(machine_id):
    path = MACHINES_DIR / f"{machine_id}.json"
    if not path.exists():
        return machine_id, ""
    data = json.loads(path.read_text())
    parts = [data.get("chip"), f"{data['ram_gb']} GB" if data.get("ram_gb") else None]
    return " · ".join(p for p in parts if p) or machine_id, data.get("notes") or ""


def score_title(runs):
    metrics = {r["metric"] for r in runs if r["metric"]}
    return "Accuracy" if metrics <= {"accuracy"} else " / ".join(sorted(metrics))


# --------------------------------------------------------------------------
# Per-machine report
# --------------------------------------------------------------------------
def machine_report(task, machine_id, runs, how_to_link):
    done = [r for r in runs if r["completed"]]
    not_done = [r for r in runs if not r["completed"]]
    label, notes = machine_label(machine_id)
    title = score_title(done)
    meta = ["Quant", "Context (reasoning)", "Runtime"]

    def meta_cells(r):
        return [fmt(r["quant"]), fmt_ctx(r), fmt(r["runtime"])]

    out = [MARKER, "", f"# {task} results — {machine_id}", "",
           f"Machine: {label}." + (f" {notes}" if notes else ""), "",
           f"{len(done)} completed and {len(not_done)} not completed runs. "
           f"Speed metrics are explained in [how-to-compute-tok-s.md]({how_to_link}).",
           "Quant, context, reasoning, and runtime come from the run metadata when present, then from "
           "`run-metadata.json`, then (quant only) from the model name; `—` means unknown.",
           "", f"## {title} (completed runs)", ""]
    rows = [
        [display_model(r["model"])] + meta_cells(r)
        + [fmt(r["accuracy"], "pct"), r["samples"], r["date"], f"`{r['eval_id']}`"]
        for r in sorted(done, key=lambda r: -(r["accuracy"] or 0))
    ]
    out.append(md_table(["Model"] + meta + [title, "Samples", "Date", "Eval ID"], rows,
                        right=(title, "Samples")))

    out += ["", "## Speed (completed runs)", ""]
    speed_headers = ["Model"] + meta + [
        "Per-call tok/s (avg)", "Per-call tok/s (min–max)", "Wall-clock tok/s",
        "Output tokens", "Eval ID",
    ]
    rows = [
        [display_model(r["model"])] + meta_cells(r)
        + [fmt(r["tps_avg"], "rate"), fmt_range(r["tps_min"], r["tps_max"]),
           fmt(r["wall_tps"], "rate"), fmt(r["out_tokens"], "int"), f"`{r['eval_id']}`"]
        for r in sorted(done, key=lambda r: -(r["tps_avg"] or 0))
    ]
    out.append(md_table(speed_headers, rows, right=tuple(speed_headers[4:8])))

    if not_done:
        out += ["", "## Not completed runs", "",
                "Samples counts only the samples that produced model output (of the total in "
                "the dataset); the rest errored or never ran. Stats cover only those "
                "samples. No accuracy is recorded for these runs.", ""]
        headers = ["Date", "Model", "Eval ID", "Status", "Samples", "Output tokens",
                   "Per-call tok/s (avg)", "Per-call tok/s (min–max)", "Wall-clock tok/s"]
        rows = []
        for r in sorted(not_done, key=lambda r: r["file"]):
            total = f"/{r['total_samples']}" if r["total_samples"] else ""
            rows.append([
                r["date"], display_model(r["model"]), f"`{r['eval_id']}`",
                r["status"] or "interrupted (no header)", f"{r['samples']}{total}",
                fmt(r["out_tokens"], "int"), fmt(r["tps_avg"], "rate"),
                fmt_range(r["tps_min"], r["tps_max"]), fmt(r["wall_tps"], "rate"),
            ])
        out.append(md_table(headers, rows, right=tuple(headers[4:])))
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# Cross-machine comparison
# --------------------------------------------------------------------------
def comparison_report(task, by_machine):
    machines = sorted(by_machine)
    configs = {}  # (model, quant, ctx, reasoning) -> {machine: latest completed run}
    for machine_id in machines:
        for r in sorted((r for r in by_machine[machine_id] if r["completed"]),
                        key=lambda r: r["file"]):
            configs.setdefault(
                (r["model"], r["quant"], r["ctx"], r["reasoning"]), {})[machine_id] = r
    title = score_title([r for m in machines for r in by_machine[m] if r["completed"]])

    def table(sort_key, cell, machine_header="{}"):
        machine_headers = [machine_header.format(m) for m in machines]
        headers = ["Model", "Quant", "Context (reasoning)"] + machine_headers
        ordered = sorted(
            configs.items(),
            key=lambda item: -max((sort_key(r) or 0) for r in item[1].values()),
        )
        rows = [
            [display_model(model), fmt(quant), fmt_ctx(next(iter(per_machine.values())))]
            + [cell(per_machine[m]) if m in per_machine else DASH for m in machines]
            for (model, quant, _ctx, _reasoning), per_machine in ordered
        ]
        return md_table(headers, rows, right=tuple(machine_headers))

    labels = [f"- `{m}`: {machine_label(m)[0]}" for m in machines]
    return "\n".join([
        MARKER, "", f"# {task} — machine comparison", "",
        "Only completed runs are shown. When a model was run more than once with the "
        "same quantization, context, and reasoning setting on a machine, the latest "
        "run is used. "
        "Per-machine details are in `<machine-id>/results.md`.", "",
        *labels, "",
        f"## {title} by machine", "",
        table(lambda r: r["accuracy"], lambda r: fmt(r["accuracy"], "pct")), "",
        "## Per-call tok/s by machine", "",
        "Each cell is `avg (min–max)`. Speed depends on the machine; compare the same "
        "model across columns.", "",
        table(lambda r: r["tps_avg"], fmt_speed, "{} (avg (min–max))"), "",
    ])


# --------------------------------------------------------------------------
# Main
# --------------------------------------------------------------------------
def write_generated(path, content, force):
    first_line = path.read_text().splitlines()[:1] if path.exists() else [MARKER]
    if not force and first_line != [MARKER]:
        print(f"error: {path} was not generated by this script; move it away or use --force",
              file=sys.stderr)
        return False
    path.write_text(content)
    print(f"wrote {path.relative_to(RESULTS_DIR.parent)}")
    return True


def main():
    parser = argparse.ArgumentParser(description="Generate results tables from .eval logs.")
    parser.add_argument("--task", help="only this task, e.g. humaneval")
    parser.add_argument("--machine", help="only write this machine's results.md, e.g. m1-8gb")
    parser.add_argument("--force", action="store_true",
                        help="overwrite files that were not generated by this script")
    args = parser.parse_args()

    ok, found = True, False
    for task_dir in sorted(p for p in RESULTS_DIR.iterdir() if p.is_dir()):
        if args.task and task_dir.name != args.task:
            continue
        by_machine = {}  # always read every machine so comparison.md stays complete
        for machine_dir in sorted(p for p in task_dir.iterdir() if p.is_dir()):
            logs = sorted(machine_dir.glob("*.eval"))
            if not logs:
                continue
            overrides = load_overrides(machine_dir)
            runs = [r for r in (read_log(p) for p in logs) if r]
            for run in runs:
                resolve_metadata(run, overrides, machine_dir.name)
            by_machine[machine_dir.name] = runs
            if not args.machine or args.machine == machine_dir.name:
                report = machine_report(task_dir.name, machine_dir.name, runs,
                                        "../../how-to-compute-tok-s.md")
                ok &= write_generated(machine_dir / "results.md", report, args.force)
        if by_machine:
            found = True
            ok &= write_generated(task_dir / "comparison.md",
                                  comparison_report(task_dir.name, by_machine), args.force)
    if not found:
        print("no .eval logs found", file=sys.stderr)
        return 1
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
